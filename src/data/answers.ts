const FALLBACK = [
  'Bilmiyorum. Karışık hissediyorum.',
  'Bazen öyle, bazen değil.',
  'Anlatması zor.',
  'Bunu hiç düşünmemiştim.',
];

function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function answerFor(profile: Profile, q: Question): QaPair {
  const bank = LOFI[profile.id];
  const options = bank[q.id];
  const answer = options && options.length > 0 ? pick(options) : pick(FALLBACK);
  return { question: q, answer };
}
